"""Snapshot, restore, and manifest for the fixed-materialization A/B framework.

The benchmark's current lifecycle ingests + recalls + cleans up per question,
so there's no point where all 500 questions are materialized simultaneously.
This module provides:

  * **Manifest**: per-question metadata (project_id, gold_session_ids, turn_ids,
    turn_id→session_id map, row count) + dataset checksum,
    code version, embedding info, and ``retrieval_as_of`` timestamp.
  * **Snapshot**: export ``episodes`` and ``episode_turns`` rows for
    ``project_id LIKE 'lme_%'`` using PostgreSQL COPY (filtered, not whole-table).
  * **Restore**: clear benchmark rows, load COPY files back, verify counts.

The manifest is the ground truth for recall-only mode — it reconstructs the
in-memory side-maps (``turn_id→session_id``, ``turn_id→content``) needed for
recall@10 scoring without re-ingesting.

Author:  Weft Recall Reliability Plan — Phase 2
"""

from __future__ import annotations

import asyncio
import gzip
import hashlib
import json
import logging
import os
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

import asyncpg

logger = logging.getLogger(__name__)

# Table names that participate in the snapshot. Turn-mode only —
# memories are NOT part of the snapshot/restore contract.
_SNAPSHOT_TABLES = ["episodes", "episode_turns"]
_PROJECT_PREFIX = "lme_"
_COMPLETE_MARKER = ".complete"

# COPY archives intentionally exclude generated columns.  In particular,
# episode_turns.search_tsv is generated by the v51 FTS migration and cannot be
# supplied in a COPY input row.  Keep this list stable so an archive remains
# restorable after additive schema migrations.  source_session_id is included
# because it is ordinary writable lineage data, not a generated column.
EPISODE_SNAPSHOT_COLUMNS = (
    "id", "title", "summary", "project_id", "agent_id", "started_at",
    "ended_at", "status", "token_count", "created_at", "updated_at",
    "user_id", "expires_at", "graduated_memory_id", "embedding",
)
EPISODE_TURN_SNAPSHOT_COLUMNS = (
    "id", "episode_id", "turn_index", "role", "content", "occurred_at",
    "embedding", "trace_id", "source_session_id", "importance_score",
    "token_count", "user_id",
    "created_at", "usefulness_score", "usefulness_count", "last_boosted_at",
)
_SNAPSHOT_COLUMNS = {
    "episodes": EPISODE_SNAPSHOT_COLUMNS,
    "episode_turns": EPISODE_TURN_SNAPSHOT_COLUMNS,
}


@dataclass
class QuestionManifest:
    """Per-question metadata persisted in the manifest."""

    question_id: str
    question_type: str
    project_id: str
    gold_session_ids: list[str]
    turn_ids: list[str] = field(default_factory=list)
    turn_session_map: dict[str, str] = field(default_factory=dict)
    turn_content_map: dict[str, str] = field(default_factory=dict)
    row_count: int = 0


@dataclass
class Manifest:
    """Top-level manifest for a materialized snapshot."""

    snapshot_name: str
    dataset_path: str
    dataset_checksum: str
    code_version: str
    embedding_provider: str
    embedding_model: str
    embedding_dimensions: int
    retrieval_as_of: str  # ISO 8601 timezone-aware
    questions: list[QuestionManifest] = field(default_factory=list)
    total_episodes: int = 0
    total_turns: int = 0

    def to_json(self) -> str:
        return json.dumps(
            {
                "snapshot_name": self.snapshot_name,
                "dataset_path": self.dataset_path,
                "dataset_checksum": self.dataset_checksum,
                "code_version": self.code_version,
                "embedding": {
                    "provider": self.embedding_provider,
                    "model": self.embedding_model,
                    "dimensions": self.embedding_dimensions,
                },
                "retrieval_as_of": self.retrieval_as_of,
                "total_episodes": self.total_episodes,
                "total_turns": self.total_turns,
                "questions": [
                    {
                        "question_id": q.question_id,
                        "question_type": q.question_type,
                        "project_id": q.project_id,
                        "gold_session_ids": q.gold_session_ids,
                        "turn_ids": q.turn_ids,
                        "turn_session_map": q.turn_session_map,
                        "row_count": q.row_count,
                    }
                    for q in self.questions
                ],
            },
            indent=2,
        )

    @classmethod
    def from_json(cls, text: str) -> "Manifest":
        data = json.loads(text)
        questions = [
            QuestionManifest(
                question_id=q["question_id"],
                question_type=q["question_type"],
                project_id=q["project_id"],
                gold_session_ids=q["gold_session_ids"],
                turn_ids=q["turn_ids"],
                turn_session_map=q["turn_session_map"],
                # Older manifests duplicated full turn text here. Keep loading
                # them for compatibility, but new manifests store source text
                # only in the COPY archive/database.
                turn_content_map=q.get("turn_content_map", {}),
                row_count=q["row_count"],
            )
            for q in data["questions"]
        ]
        emb = data["embedding"]
        return cls(
            snapshot_name=data["snapshot_name"],
            dataset_path=data["dataset_path"],
            dataset_checksum=data["dataset_checksum"],
            code_version=data["code_version"],
            embedding_provider=emb["provider"],
            embedding_model=emb["model"],
            embedding_dimensions=emb["dimensions"],
            retrieval_as_of=data["retrieval_as_of"],
            questions=questions,
            total_episodes=data["total_episodes"],
            total_turns=data["total_turns"],
        )

    def get_question(self, question_id: str) -> QuestionManifest | None:
        for q in self.questions:
            if q.question_id == question_id:
                return q
        return None


def dataset_checksum(dataset_path: Path) -> str:
    """SHA-256 checksum of the dataset file."""
    h = hashlib.sha256()
    with dataset_path.open("rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()


def code_version() -> str:
    """Current git commit hash, or 'unknown' if not a git repo."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            capture_output=True, text=True, timeout=5,
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except Exception:
        pass
    return "unknown"


def snapshot_dir(base: Path, name: str) -> Path:
    """Directory for a named snapshot."""
    return base / name


async def snapshot(
    pool: asyncpg.Pool,
    *,
    name: str,
    manifest: Manifest,
    base_dir: Path,
) -> Path:
    """Export episodes + episode_turns (filtered by lme_%) to compressed COPY files.

    Uses PostgreSQL COPY with a filtered query (not pg_dump, which exports
    whole tables). Episodes first (parent), then episode_turns (child with FK).

    Returns the snapshot directory path.
    """
    sdir = snapshot_dir(base_dir, name)
    sdir.mkdir(parents=True, exist_ok=True)

    # Publish only after both streams succeed. A manifest without a marker is
    # not a usable snapshot after an interrupted export.
    manifest_path = sdir / "manifest.json"
    marker_path = sdir / _COMPLETE_MARKER
    marker_path.unlink(missing_ok=True)
    manifest_path.write_text(manifest.to_json(), encoding="utf-8")

    # Export episodes (filtered by project_id LIKE 'lme_%')
    episodes_copy = sdir / "episodes.csv.gz"
    await _copy_out_filtered(
        pool, episodes_copy,
        "SELECT " + ", ".join(EPISODE_SNAPSHOT_COLUMNS)
        + " FROM episodes WHERE project_id LIKE 'lme_%'",
    )

    # Export episode_turns (filtered by episode_id join to lme_ episodes).
    # Keep generated columns out of the archive; they are rebuilt by Postgres.
    turns_copy = sdir / "episode_turns.csv.gz"
    await _copy_out_filtered(
        pool, turns_copy,
        "SELECT " + ", ".join(
            f"t.{column}" for column in EPISODE_TURN_SNAPSHOT_COLUMNS
        )
        + " FROM episode_turns t JOIN episodes e ON t.episode_id = e.id "
        "WHERE e.project_id LIKE 'lme_%'",
    )

    marker_path.write_text("ok\n", encoding="utf-8")
    logger.info(
        "snapshot '%s' written to %s (episodes=%d, turns=%d)",
        name, sdir, manifest.total_episodes, manifest.total_turns,
    )
    return sdir


async def _copy_out_filtered(
    pool: asyncpg.Pool, path: Path, copy_sql: str,
) -> None:
    """Run a filtered COPY directly into a compressed output stream.

    The LongMemEval turn corpus contains millions of rows.  Buffering the
    complete COPY payload in ``BytesIO`` can exhaust memory or leave a zero-
    byte artifact when the client process is interrupted.  ``asyncpg``
    supports an async output callback, so stream each COPY chunk directly to
    gzip instead.  The query remains filtered (never a whole-table dump).
    """
    async with pool.acquire() as conn:
        # Low compression keeps the multi-gigabyte benchmark export bounded by
        # I/O rather than CPU. Write to a temporary sibling so interruption
        # cannot leave a file that looks like a completed snapshot.
        temp_path = path.with_suffix(path.suffix + ".partial")
        temp_path.unlink(missing_ok=True)
        with gzip.open(temp_path, "wb", compresslevel=1) as output:
            async def write_chunk(chunk: bytes) -> None:
                output.write(chunk)

            await conn.copy_from_query(
                copy_sql,
                output=write_chunk,
                format="csv",
                header=True,
            )
        if temp_path.stat().st_size == 0:
            temp_path.unlink(missing_ok=True)
            raise RuntimeError(f"COPY produced an empty snapshot: {path}")
        temp_path.replace(path)


async def restore_snapshot(
    pool: asyncpg.Pool,
    *,
    sdir: Path,
    expected_manifest: Manifest | None = None,
) -> Manifest:
    """Clear benchmark DB rows and load from snapshot COPY files.

    Returns the manifest loaded from the snapshot. If ``expected_manifest``
    is provided, verifies dataset checksum and code version match.
    """
    manifest_path = sdir / "manifest.json"
    marker_path = sdir / _COMPLETE_MARKER
    if not manifest_path.exists():
        raise FileNotFoundError(f"manifest.json not found in {sdir}")
    if not marker_path.exists():
        raise RuntimeError(
            f"snapshot is not marked complete: {sdir}; refusing restore"
        )
    for filename in ("episodes.csv.gz", "episode_turns.csv.gz"):
        path = sdir / filename
        if not path.exists() or path.stat().st_size == 0:
            raise RuntimeError(f"snapshot archive missing or empty: {path}")
    manifest = Manifest.from_json(manifest_path.read_text(encoding="utf-8"))

    if expected_manifest is not None:
        if manifest.dataset_checksum != expected_manifest.dataset_checksum:
            raise ValueError(
                f"Dataset checksum mismatch: snapshot={manifest.dataset_checksum} "
                f"expected={expected_manifest.dataset_checksum}"
            )

    # Clear existing benchmark rows (dependency-safe order)
    await _clear_benchmark_rows(pool)

    # Load episodes first (parent table)
    episodes_copy = sdir / "episodes.csv.gz"
    if episodes_copy.exists():
        await _copy_in_filtered(pool, episodes_copy, "episodes")

    # Load episode_turns (child table with FK to episodes)
    turns_copy = sdir / "episode_turns.csv.gz"
    if turns_copy.exists():
        await _copy_in_filtered(pool, turns_copy, "episode_turns")

    # Verify row counts
    ep_count = await pool.fetchval(
        "SELECT count(*) FROM episodes WHERE project_id LIKE 'lme_%'"
    )
    turn_count = await pool.fetchval(
        "SELECT count(*) FROM episode_turns t JOIN episodes e ON t.episode_id = e.id "
        "WHERE e.project_id LIKE 'lme_%'"
    )
    emb_count = await pool.fetchval(
        "SELECT count(*) FROM episode_turns t "
        "JOIN episodes e ON t.episode_id = e.id "
        "WHERE e.project_id LIKE 'lme_%' AND t.embedding IS NOT NULL"
    )
    logger.info(
        "restored snapshot: episodes=%d (expected %d), turns=%d (expected %d), embeddings=%d (expected %d)",
        ep_count, manifest.total_episodes,
        turn_count, manifest.total_turns,
        emb_count, manifest.total_turns,
    )
    if (
        int(ep_count or 0) != manifest.total_episodes
        or int(turn_count or 0) != manifest.total_turns
        or int(emb_count or 0) != manifest.total_turns
    ):
        raise RuntimeError(
            "restored snapshot failed integrity check; refusing to continue "
            f"(episodes={ep_count}/{manifest.total_episodes}, "
            f"turns={turn_count}/{manifest.total_turns}, "
            f"embeddings={emb_count}/{manifest.total_turns})"
        )

    return manifest


async def _clear_benchmark_rows(pool: asyncpg.Pool) -> None:
    """Delete all benchmark rows (lme_% projects) in dependency-safe order."""
    # episode_turns first (FK to episodes), then episodes, then memories
    await pool.execute(
        "DELETE FROM episode_turns WHERE episode_id IN "
        "(SELECT id FROM episodes WHERE project_id LIKE 'lme_%')"
    )
    await pool.execute(
        "DELETE FROM belief_claims WHERE evidence_turn_ids && ("
        "SELECT COALESCE(array_agg(et.id), ARRAY[]::text[]) "
        "FROM episode_turns et JOIN episodes e ON et.episode_id = e.id "
        "WHERE e.project_id LIKE 'lme_%'"
        ")"
    )
    await pool.execute("DELETE FROM episodes WHERE project_id LIKE 'lme_%'")
    await pool.execute("DELETE FROM memories WHERE project_id LIKE 'lme_%'")


async def _gzip_chunks(path: Path, *, chunk_size: int = 1024 * 1024):
    """Yield decompressed COPY bytes without buffering the archive."""
    with gzip.open(path, "rb") as source:
        while True:
            chunk = source.read(chunk_size)
            if not chunk:
                break
            yield chunk


async def _copy_in_filtered(
    pool: asyncpg.Pool, path: Path, table: str,
) -> None:
    """Stream a snapshot using the archive's compatible writable columns.

    Archives created before source_session_id was added do not carry that
    header. Detect the header before COPY so those canonical snapshots remain
    restorable; newly-created archives use the full current column set.
    """
    columns = _SNAPSHOT_COLUMNS.get(table)
    if columns is None:
        raise ValueError(f"unsupported snapshot table: {table}")

    with gzip.open(path, "rb") as source:
        header = source.readline().decode("utf-8").strip().split(",")
    archive_columns = tuple(header)
    if not archive_columns:
        raise ValueError(f"snapshot archive has no header: {path}")
    if set(archive_columns) - set(columns):
        raise ValueError(
            f"snapshot archive has unsupported columns for {table}: "
            f"{sorted(set(archive_columns) - set(columns))}"
        )
    columns = archive_columns

    async with pool.acquire() as conn:
        await conn.copy_to_table(
            table,
            columns=columns,
            source=_gzip_chunks(path),
            format="csv",
            header=True,
        )


async def verify_snapshot(
    pool: asyncpg.Pool,
    manifest: Manifest,
) -> bool:
    """Verify that the DB state matches the manifest's expected counts.

    Checks:
      - Total episode count for lme_% projects
      - Total turn count for lme_% projects
      - Per-question turn count (sampled)
    """
    ep_count = await pool.fetchval(
        "SELECT count(*) FROM episodes WHERE project_id LIKE 'lme_%'"
    )
    if ep_count != manifest.total_episodes:
        logger.error(
            "verify: episode count mismatch: db=%d, manifest=%d",
            ep_count, manifest.total_episodes,
        )
        return False

    turn_count = await pool.fetchval(
        "SELECT count(*) FROM episode_turns t JOIN episodes e ON t.episode_id = e.id "
        "WHERE e.project_id LIKE 'lme_%'"
    )
    if turn_count != manifest.total_turns:
        logger.error(
            "verify: turn count mismatch: db=%d, manifest=%d",
            turn_count, manifest.total_turns,
        )
        return False

    # Every turn must have a vector for hybrid vector + keyword recall. The
    # source text remains in the row/COPY archive, but a missing vector makes
    # the fixed-materialization baseline incomplete.
    emb_count = await pool.fetchval(
        "SELECT count(*) FROM episode_turns t "
        "JOIN episodes e ON t.episode_id = e.id "
        "WHERE e.project_id LIKE 'lme_%' AND t.embedding IS NOT NULL"
    )
    if emb_count != manifest.total_turns:
        logger.error(
            "verify: embedding count mismatch: db=%d, expected=%d",
            emb_count, manifest.total_turns,
        )
        return False

    logger.info(
        "verify: snapshot OK (episodes=%d, turns=%d, embeddings=%d)",
        ep_count, turn_count, emb_count,
    )
    return True
